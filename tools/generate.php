<?php

declare(strict_types=1);

/*
 * Writes stubs/gen_<group>.stub.php and src/gen_<group>.c for the libvlc functions of a header
 * group whose every parameter and result is a plain shape: a handle, an integer, a float, a bool,
 * a string or a void * address. Functions with any other shape (callbacks, out-pointers, arrays,
 * structs) are listed as hand-written and left to the group's own stub and source.
 *
 *   php84 tools/generate.php <group> [path/to/include/vlc]
 *   groups: player, lists, discovery, vlm, dialog
 */

const GROUPS = [
    'player' => ['libvlc_media_player.h'],
    'lists' => ['libvlc_media_list.h', 'libvlc_media_list_player.h', 'libvlc_media_library.h'],
    'discovery' => ['libvlc_media_discoverer.h', 'libvlc_renderer_discoverer.h'],
    'vlm' => ['libvlc_vlm.h'],
    'dialog' => ['libvlc_dialog.h'],
];

const HANDLES = [
    'libvlc_instance_t', 'libvlc_media_t', 'libvlc_media_player_t', 'libvlc_media_list_t', 'libvlc_media_list_player_t',
    'libvlc_media_library_t', 'libvlc_media_discoverer_t', 'libvlc_renderer_discoverer_t', 'libvlc_renderer_item_t',
    'libvlc_event_manager_t', 'libvlc_equalizer_t', 'libvlc_dialog_id', 'libvlc_audio_output_t',
    'libvlc_audio_output_device_t', 'libvlc_track_description_t',
];

/* Parameters libvlc documents as accepting NULL. */
const NULLABLE = [
    'libvlc_media_player_set_media.p_md', 'libvlc_media_player_set_equalizer.p_equalizer',
    'libvlc_media_player_set_renderer.p_item',
];

/* Not exported by the 3.0.24 dylib: declared, but nothing to link. */
const UNEXPORTED = ['libvlc_media_player_set_evas_object', 'libvlc_vlm_get_media_instance_title',
    'libvlc_vlm_get_media_instance_chapter', 'libvlc_vlm_get_media_instance_seekable'];

/*
 * Plain shapes written by hand: the ones that free libvlc memory (so the freed handles read 0 from
 * pointer()), and the format setters the audio and video callbacks size their buffers from.
 */
const FREES = ['libvlc_track_description_list_release', 'libvlc_audio_output_list_release',
    'libvlc_audio_output_device_list_release', 'libvlc_audio_equalizer_release',
    'libvlc_media_discoverer_release', 'libvlc_renderer_discoverer_release',
    'libvlc_audio_set_format', 'libvlc_video_set_format'];

/* Reference-counted classes: their *_retain / _hold add a reference, their *_release drops one. */
const REFCOUNTED = ['libvlc_instance_t', 'libvlc_media_t', 'libvlc_media_player_t', 'libvlc_media_list_t',
    'libvlc_media_list_player_t', 'libvlc_media_library_t', 'libvlc_renderer_item_t'];

/* Functions whose returned handle is a new reference the caller releases (libvlc's docs). */
const NEW_REF = ['libvlc_media_player_new', 'libvlc_media_player_new_from_media', 'libvlc_media_player_get_media',
    'libvlc_media_list_new', 'libvlc_media_list_item_at_index', 'libvlc_media_list_media',
    'libvlc_media_list_player_new', 'libvlc_media_list_player_get_media_player',
    'libvlc_media_library_new', 'libvlc_media_library_media_list', 'libvlc_media_discoverer_media_list'];

const INTEGERS = ['int', 'unsigned', 'unsigned int', 'int64_t', 'uint32_t', 'size_t', 'libvlc_time_t', 'libvlc_event_type_t'];

[$group, $dir] = [$argv[1] ?? '', $argv[2] ?? '/Applications/VLC.app/Contents/MacOS/include/vlc'];
if (! isset(GROUPS[$group])) {
    fwrite(STDERR, 'groups: '.implode(', ', array_keys(GROUPS))."\n");
    exit(1);
}

/** int, string, ?string, float, bool, handle class, 'addr' (void *), or null for a hand-written shape. */
function shape(string $type, bool $nullable): ?array
{
    $type = trim(preg_replace('/\s+/', ' ', str_replace('*', ' * ', $type)));
    $bare = trim(preg_replace('/\b(const|struct)\b/', '', $type));
    if (preg_match('/^(\w+) \*$/', $bare, $m) && in_array($m[1], HANDLES, true)) {
        return ['handle', $m[1], $nullable];
    }
    if ($bare === 'char *') {
        return [str_contains($type, 'const') ? 'cstr' : 'ownstr', null, true];
    }
    if ($bare === 'void *') {
        return ['addr', null, false];
    }
    if (in_array($bare, INTEGERS, true) || preg_match('/^libvlc_\w+_t$/', $bare) && ! in_array($bare, HANDLES, true) && $bare !== 'libvlc_video_viewpoint_t') {
        return ['int', $bare, false];
    }
    if ($bare === 'float') {
        return ['float', null, false];
    }
    if ($bare === 'bool') {
        return ['bool', null, false];
    }

    return null;
}

function php_type(array $s): string
{
    return match ($s[0]) {
        'handle' => ($s[2] ? '?' : '').$s[1],
        'cstr', 'ownstr' => '?string',
        'addr', 'int' => 'int',
        'float' => 'float',
        'bool' => 'bool',
    };
}

$stub = "<?php\n\n/** @generate-class-entries */\n\n/* Generated by tools/generate.php {$group}. Do not edit; rerun the tool. Implementations: src/gen_{$group}.c. */\n";
$c = "/* Generated by tools/generate.php {$group}. Do not edit; rerun the tool. */\n#include \"runtime.h\"\n#include \"../stubs/gen_{$group}_arginfo.h\"\n";
$hand = [];
$count = 0;

foreach (GROUPS[$group] as $header) {
    $source = preg_replace('#/\*.*?\*/#s', '', file_get_contents("{$dir}/{$header}"));
    preg_match_all('/LIBVLC_API\s+(?:VLC_FORWARD_DECLARE_OBJECT\(([^)]*)\)\s*)?([^;{(]*?)\b(libvlc_\w+)\s*\(([^;]*?)\)\s*;/s', $source, $decls, PREG_SET_ORDER);
    foreach ($decls as [, $fwd, $ret, $name, $params]) {
        if (in_array($name, UNEXPORTED, true)) {
            continue;
        }
        $ret = trim($fwd !== '' ? $fwd : $ret);
        $retShape = $ret === 'void' ? ['void'] : shape($ret, true);
        $args = [];
        foreach (trim($params) === 'void' ? [] : array_map('trim', explode(',', $params)) as $p) {
            if (! preg_match('/^(.*?[\s*])(\w+)$/s', $p, $m)) {
                $args = null;
                break;
            }
            $s = shape($m[1], in_array("{$name}.{$m[2]}", NULLABLE, true));
            if ($s === null) {
                $args = null;
                break;
            }
            $args[] = [$m[2], $s, trim(preg_replace('/\s+/', ' ', $m[1]))];
        }
        if ($args === null || $retShape === null || in_array($name, FREES, true)) {
            $hand[] = $name;
            continue;
        }
        $count++;

        $phpRet = $retShape === ['void'] ? 'void' : ($retShape[0] === 'handle' ? '?'.$retShape[1] : php_type($retShape));
        $stub .= "\nfunction {$name}(".implode(', ', array_map(fn ($a) => php_type($a[1]).' $'.$a[0], $args))."): {$phpRet} {}\n";

        $decl = $parse = $pre = $call = [];
        foreach ($args as $i => [$n, $s, $ctype]) {
            $no = $i + 1;
            switch ($s[0]) {
                case 'handle':
                    $decl[] = "\tzval *z_{$n};";
                    $parse[] = $s[2] ? "\t\tZ_PARAM_OBJECT_OF_CLASS_OR_NULL(z_{$n}, vlc_ce_{$s[1]})" : "\t\tZ_PARAM_OBJECT_OF_CLASS(z_{$n}, vlc_ce_{$s[1]})";
                    $pre[] = $s[2]
                        ? "\t{$s[1]} *{$n} = NULL;\n\tif (z_{$n} != NULL) {\n\t\t{$n} = vlc_handle_arg(z_{$n}, {$no});\n\t\tif (EG(exception)) {\n\t\t\tRETURN_THROWS();\n\t\t}\n\t}"
                        : "\tVLC_ARG({$s[1]}, {$n}, z_{$n}, {$no});";
                    $call[] = $n;
                    break;
                case 'cstr':
                case 'ownstr':
                    $decl[] = "\tzend_string *{$n};";
                    $parse[] = "\t\tZ_PARAM_STR_OR_NULL({$n})";
                    $call[] = "{$n} != NULL ? ZSTR_VAL({$n}) : NULL";
                    break;
                case 'addr':
                    $decl[] = "\tzend_long {$n};";
                    $parse[] = "\t\tZ_PARAM_LONG({$n})";
                    $call[] = "(void *) (uintptr_t) {$n}";
                    break;
                case 'int':
                    $decl[] = "\tzend_long {$n};";
                    $parse[] = "\t\tZ_PARAM_LONG({$n})";
                    $call[] = "({$s[1]}) {$n}";
                    break;
                case 'float':
                    $decl[] = "\tdouble {$n};";
                    $parse[] = "\t\tZ_PARAM_DOUBLE({$n})";
                    $call[] = "(float) {$n}";
                    break;
                case 'bool':
                    $decl[] = "\tbool {$n};";
                    $parse[] = "\t\tZ_PARAM_BOOL({$n})";
                    $call[] = $n;
                    break;
            }
        }
        $invoke = "{$name}(".implode(', ', $call).')';
        $first = $args[0] ?? null;
        $counted = $first !== null && $first[1][0] === 'handle' && in_array($first[1][1], REFCOUNTED, true);
        $own = $counted ? substr($first[1][1], 0, -2) : '';   /* libvlc_media_player_t -> libvlc_media_player */
        if ($counted && in_array($name, ["{$own}_retain", "{$own}_hold"], true)) {
            $pre[] = "\tvlc_ref_add({$first[0]}, vlc_ce_{$first[1][1]});";
        }
        /*
         * Around libvlc's release: event callables are detached while the object still exists; the
         * player's other callback records go only once libvlc is done calling them.
         */
        $after = '';
        if ($counted && $name === "{$own}_release") {
            $pre[] = "\tvlc_ref_releasing({$first[0]}, vlc_ce_{$first[1][1]});";
            $after = "\n\tvlc_ref_drop({$first[0]}, vlc_ce_{$first[1][1]});";
        }
        /* The list player holds its player: that hold is a reference the player's count includes. */
        if ($name === 'libvlc_media_list_player_set_media_player') {
            $pre[] = "\tvoid *held = vlc_held_set(p_mlp, p_mi);";
            $after = "\n\tvlc_held_released(held);";
        }
        if ($name === 'libvlc_media_list_player_get_media_player') {
            $after = "\n\tvlc_held_seen(p_mlp, result);";
        }
        /* libvlc stops the services discovery it holds without checking for one: none before a successful start. */
        if ($name === 'libvlc_media_discoverer_stop') {
            $pre[] = "\tif (!VLC_PROBE_OFF(\"vlc-discoverer-not-running\") && !libvlc_media_discoverer_is_running(p_mdis)) {\n"
                ."\t\tzend_argument_value_error(1, \"is not running\"); /* binding:vlc-discoverer-not-running */\n"
                ."\t\tRETURN_THROWS();\n\t}";
        }
        /* The VLM's event manager goes with the VLM. */
        if ($name === 'libvlc_vlm_release') {
            $pre[] = "\tvlc_events_gone(p_instance);";
        }
        $newRef = $retShape[0] === 'handle' && in_array($name, NEW_REF, true);
        $result = match ($retShape[0]) {
            'void' => "\t{$invoke};",
            'handle' => match (true) {
                $newRef => "\t{$retShape[1]} *result = {$invoke};\n\tvlc_ref_add(result, vlc_ce_{$retShape[1]});\n\tvlc_box(return_value, result, vlc_ce_{$retShape[1]});",
                $retShape[1] === 'libvlc_event_manager_t' => "\tvlc_box_em(return_value, {$invoke}, {$first[0]});",
                default => "\tvlc_box(return_value, {$invoke}, vlc_ce_{$retShape[1]});",
            },
            'cstr' => "\tvlc_string_or_null(return_value, {$invoke});",
            'ownstr' => "\tvlc_owned_string(return_value, {$invoke});",
            'addr' => "\tRETURN_LONG((zend_long) (uintptr_t) {$invoke});",
            'int' => "\tRETURN_LONG({$invoke});",
            'float' => "\tRETURN_DOUBLE({$invoke});",
            'bool' => "\tRETURN_BOOL({$invoke});",
        };
        /* libvlc frees the dialog id in these: its handle is released with it. */
        if (in_array($name, ['libvlc_dialog_post_login', 'libvlc_dialog_post_action', 'libvlc_dialog_dismiss'], true)) {
            $result = "\tint result = {$invoke};\n\tvlc_release(p_id, vlc_ce_libvlc_dialog_id);\n\tRETURN_LONG(result);";
        }
        $n = count($args);
        $body = $n === 0 ? "\tZEND_PARSE_PARAMETERS_NONE();\n" : implode("\n", $decl)."\n\n\tZEND_PARSE_PARAMETERS_START({$n}, {$n})\n".implode("\n", $parse)."\n\tZEND_PARSE_PARAMETERS_END();\n";
        $c .= "\nPHP_FUNCTION({$name})\n{\n{$body}".($pre !== [] ? implode("\n", $pre)."\n" : '')."{$result}{$after}\n}\n";
    }
}

$c .= "\nvoid vlc_register_gen_{$group}(void)\n{\n\tzend_register_functions(NULL, ext_functions, NULL, MODULE_PERSISTENT);\n}\n";
file_put_contents(__DIR__."/../stubs/gen_{$group}.stub.php", $stub);
file_put_contents(__DIR__."/../src/gen_{$group}.c", $c);
printf("%s: %d generated, %d hand-written: %s\n", $group, $count, count($hand), implode(' ', $hand));
