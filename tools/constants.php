<?php

declare(strict_types=1);

/*
 * Writes stubs/constants.stub.php from the libvlc headers (deprecated.h excepted): every
 * enumerator of every enum and the integer #defines, each registered with @cvalue so the value
 * is the header's.
 *
 *   php84 tools/constants.php [path/to/include/vlc]
 */

$dir = $argv[1] ?? '/Applications/VLC.app/Contents/MacOS/include/vlc';
$headers = array_filter(glob("{$dir}/libvlc*.h"), fn (string $f): bool => basename($f) !== 'deprecated.h');
if ($headers === []) {
    fwrite(STDERR, "no libvlc headers in {$dir}\n");
    exit(1);
}
sort($headers);

$names = [];
foreach ($headers as $header) {
    $source = preg_replace('#/\*.*?\*/|//[^\n]*#s', '', file_get_contents($header));
    preg_match_all('/enum\s*(\w*)\s*\{(.*?)\}\s*(\w*)/s', $source, $enums, PREG_SET_ORDER);
    foreach ($enums as [, $tag, $body, $typedef]) {
        $group = basename($header) . ': ' . ($typedef !== '' ? $typedef : ($tag !== '' ? $tag : 'enum'));
        foreach (array_filter(array_map('trim', explode(',', $body))) as $enumerator) {
            $names[$group][] = preg_replace('/\W.*$/s', '', $enumerator);
        }
    }
}
$names['defines'] = ['LIBVLC_VERSION_MAJOR', 'LIBVLC_VERSION_MINOR', 'LIBVLC_VERSION_REVISION', 'LIBVLC_VERSION_EXTRA',
    'LIBVLC_VERSION_INT', 'LIBVLC_RENDERER_CAN_AUDIO', 'LIBVLC_RENDERER_CAN_VIDEO', 'libvlc_role_Last'];

$out = "<?php\n\n/** @generate-class-entries */\n\n/* Generated by tools/constants.php from the libvlc headers. Do not edit; rerun the tool. */\n";
foreach ($names as $group => $list) {
    $out .= "\n/* {$group} */\n";
    foreach ($list as $name) {
        $out .= "\n/**\n * @var int\n * @cvalue {$name}\n */\nconst {$name} = UNKNOWN;\n";
    }
}

file_put_contents(__DIR__ . '/../stubs/constants.stub.php', $out);
printf("%d constants\n", array_sum(array_map('count', $names)));
